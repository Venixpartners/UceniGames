import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
for(const file of ['js/app.js','js/badge-share.js','sw.js'])execFileSync(process.execPath,['--check',new URL('../'+file,import.meta.url).pathname]);
const app=read('js/app.js'),share=read('js/badge-share.js'),html=read('index.html'),privacy=read('legal/privacy.html'),sw=read('sw.js');
assert.match(app,/unlockedBadges\(\)\.indexOf\(t\.dataset\.badgeChoice\)===-1/);
assert.match(app,/unlockedBadges\(\)\.indexOf\(badge\.value\)===-1/);
assert.match(app,/SCREENS\.badge_share/);
assert.match(app,/data-badge-choice/);
assert.match(app,/data-badge-platform="native"/);
assert.match(app,/data-badge-platform="download"/);
assert.match(app,/data-badge-platform="whatsapp"/);
assert.match(app,/data-badge-platform="facebook"/);
assert.match(app,/data-badge-platform="telegram"/);
assert.match(app,/data-badge-platform="linkedin"/);
assert.match(app,/data-badge-platform="x"/);
assert.match(app,/data-badge-platform="copy"/);
assert.match(html,/<script src="\/js\/badge-share\.js"><\/script>/);
assert.match(share,/navigator\.share/);
assert.match(share,/toBlob/);
assert.match(share,/noopener noreferrer/);
assert.match(share,/games\.uceni\.africa/);
assert.match(share,/no cash or material prizes/i);
assert.doesNotMatch(share,/fetch\(|axios|Paystack|Flutterwave|billing/i);
assert.match(privacy,/Optional achievement sharing/);
assert.match(sw,/"\/js\/badge-share\.js"/);
console.log('PASS: only earned badges shareable, branded PNG, native/social links, privacy, no billing');
