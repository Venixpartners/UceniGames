import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('index.html'),css=read('css/app.css'),app=read('js/app.js');
const manifest=JSON.parse(read('manifest.webmanifest')),sw=read('sw.js');
execFileSync(process.execPath,['--check',new URL('../js/app.js',import.meta.url).pathname]);
execFileSync(process.execPath,['--check',new URL('../sw.js',import.meta.url).pathname]);
assert.match(html,/name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover"/);
assert.match(html,/apple-mobile-web-app-capable/);
assert.match(html,/connection-notice/);
assert.equal(manifest.display,'standalone');
assert.equal(manifest.scope,'/');
assert.ok(manifest.icons.length>0);
assert.match(css,/@media\(max-width:360px\)/);
assert.match(css,/@media\(min-width:700px\)/);
assert.match(css,/@media\(min-width:1100px\)/);
assert.match(css, /min-height:44px/);
assert.match(app,/beforeinstallprompt/);
assert.match(app,/navigator\.serviceWorker\.register/);
assert.match(app,/navigator\.onLine/);
assert.match(sw,/if\(req\.method!=="GET"/);
assert.match(sw,/if\(!ALLOW\.has\(path\)\)return/);
assert.doesNotMatch(sw,/cache\.put\(.*token|localStorage|api\.Url/i);
console.log('PASS: responsive layouts, mobile manifest, install prompts and static-assets-only PWA cache');
